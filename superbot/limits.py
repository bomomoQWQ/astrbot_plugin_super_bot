# ---------------------------------------------------------------------------
# 活动信号（触发审查者的三种情况）
# ---------------------------------------------------------------------------

ACTIVITY_SILENCE_SEC = 180.0
"""多久没有任何工具调用算"静默"。比 STALL_THRESHOLD_SEC 短得多——
真卡住的时候没必要干等十分钟，让审查者早点看出来。"""

ACTIVITY_REPEAT_THRESHOLD = 3
"""同一条命令（参数摘要相同）连续出现几次算"原地打转"。"""

ACTIVITY_FAIL_STREAK = 5
"""连续几次工具调用全部失败算"越试越糟"。"""

TRACE_MAX_ENTRIES = 200
"""单工单最多留多少条轨迹。审查者只需要看个轮廓，不需要全量。"""

REVIEW_MAX_CHARS = 4000
"""喂给审查者的轨迹文本上限，超出只留头和尾。"""

REVIEW_COOLDOWN_SEC = 120.0
"""同一张工单两次审查之间的最短间隔。

没有它的话，一个卡住的工单会每个 tick（60 秒）叫一次模型，
一小时烧 60 次——审查是为了省钱省时，不能自己变成开销。"""

# ---------------------------------------------------------------------------
